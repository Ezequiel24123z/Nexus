import React, { useState } from 'react';
import { Plug, Unplug, Trash2, Sparkles, FolderSearch, Terminal } from 'lucide-react';
import McpCatalog from '../McpCatalog.jsx';
import { cleanError } from '../lib/format.mjs';

const emptyForm = { name: '', transport: 'stdio', command: '', args: '[]', url: '', secretRef: '', envSecrets: '{}', cwd: '' };

export default function McpView({ state, workspace, act, notify }) {
  const [form, setForm] = useState(emptyForm);
  const [busy, setBusy] = useState('');
  const [builder, setBuilder] = useState({
    name: 'Local Dev Utilities',
    description: 'Custom local MCP tools generated by NEXUS',
    toolName: 'hash_text',
    toolDesc: 'Compute SHA-256 digest of input text',
    handlerCode: 'return { sha256: crypto.createHash("sha256").update(String(args.text || "")).digest("hex") };',
  });
  const [discovered, setDiscovered] = useState([]);

  const runServer = async (name, method) => {
    setBusy(name);
    try { await act(method, { name }); }
    finally { setBusy(''); }
  };

  const scanWorkspaceMcp = async () => {
    const dir = workspace || await act('chooseWorkspace');
    if (!dir) return;
    const res = await act('discoverMcp', { workspace: dir });
    setDiscovered(res?.servers || []);
    if (!res?.servers?.length) notify('No .mcp.json or mcp.json found in that workspace.', 'info');
  };

  return (
    <div className="page-scroll">
      <div className="page-inner">
        <div className="page-header">
          <div>
            <h1>MCP Extensions</h1>
            <p className="subtitle">Connect stdio/HTTP Model Context Protocol servers, import workspace <code>.mcp.json</code>, inspect stderr logs, or scaffold custom servers on the fly.</p>
          </div>
          <button type="button" className="btn-secondary" onClick={scanWorkspaceMcp}><FolderSearch size={14} /> Import .mcp.json</button>
        </div>

        {discovered.length > 0 && (
          <div className="panel-card">
            <h3>Discovered Workspace MCP Servers</h3>
            {discovered.map(srv => (
              <div key={srv.name} className="list-row">
                <div>
                  <strong>{srv.name}</strong> <span className="pill" style={{ marginLeft: 6 }}>{srv.transport}</span>
                  <div className="hint mono">{srv.transport === 'stdio' ? `${srv.command} ${(srv.args || []).join(' ')}` : srv.url} · from {srv.source}</div>
                </div>
                <button type="button" className="btn-primary" onClick={async () => {
                  if (await act('saveMcp', srv)) { notify(`Imported MCP server "${srv.name}".`, 'ok'); setDiscovered(d => d.filter(x => x.name !== srv.name)); }
                }}>Import</button>
              </div>
            ))}
          </div>
        )}

        <div className="settings-grid">
          <div className="panel-card">
            <h2>Configure MCP Server</h2>
            <form onSubmit={async e => {
              e.preventDefault();
              try {
                const payload = { ...form, args: JSON.parse(form.args || '[]'), envSecrets: JSON.parse(form.envSecrets || '{}') };
                if (await act('saveMcp', payload)) { setForm(emptyForm); notify('MCP server saved.', 'ok'); }
              } catch (err) { notify(cleanError(err), 'error'); }
            }}>
              <label className="field"><span>Name</span><input required value={form.name} onChange={e => setForm({ ...form, name: e.target.value })} placeholder="filesystem-tools" /></label>
              <label className="field"><span>Transport</span><select value={form.transport} onChange={e => setForm({ ...form, transport: e.target.value })}><option value="stdio">Local Process (stdio)</option><option value="http">Streamable HTTP</option></select></label>
              {form.transport === 'stdio' ? (
                <>
                  <label className="field"><span>Command / Executable</span><input required value={form.command} onChange={e => setForm({ ...form, command: e.target.value })} placeholder="npx" /></label>
                  <label className="field"><span>Arguments (JSON array)</span><input className="mono" value={form.args} onChange={e => setForm({ ...form, args: e.target.value })} /></label>
                  <label className="field"><span>Working Directory (optional)</span><input value={form.cwd} onChange={e => setForm({ ...form, cwd: e.target.value })} /></label>
                  <label className="field"><span>Env Secret Refs (JSON)</span><input className="mono" value={form.envSecrets} onChange={e => setForm({ ...form, envSecrets: e.target.value })} placeholder='{"API_KEY":"CONNECTOR_API"}' /></label>
                </>
              ) : (
                <>
                  <label className="field"><span>Endpoint URL</span><input required value={form.url} onChange={e => setForm({ ...form, url: e.target.value })} placeholder="http://localhost:3333/mcp" /></label>
                  <label className="field"><span>Auth Secret Ref (optional)</span><input value={form.secretRef} onChange={e => setForm({ ...form, secretRef: e.target.value })} placeholder="CONNECTOR_MCP" /></label>
                </>
              )}
              <button className="btn-primary">Save Server</button>
            </form>
          </div>

          <div>
            <form className="panel-card" onSubmit={async e => {
              e.preventDefault();
              setBusy('scaffold');
              try {
                const res = await act('scaffoldMcp', {
                  name: builder.name,
                  description: builder.description,
                  tools: [{ name: builder.toolName, description: builder.toolDesc, inputSchema: { type: 'object', properties: { text: { type: 'string' } } }, handlerCode: builder.handlerCode }],
                });
                if (res?.created) notify(`Scaffolded & connected "${res.server}" (${res.tools.join(', ')})`, 'ok');
              } finally { setBusy(''); }
            }}>
              <div className="row" style={{ marginBottom: 8 }}><Sparkles size={16} style={{ color: 'var(--accent)' }} /><h2 style={{ margin: 0 }}>Autonomous MCP Server Builder</h2></div>
              <p className="hint">Generate a local Node.js MCP server script and hot-connect it instantly.</p>
              <div className="grid-2">
                <label className="field"><span>Server Name</span><input required value={builder.name} onChange={e => setBuilder({ ...builder, name: e.target.value })} /></label>
                <label className="field"><span>Tool Name</span><input required value={builder.toolName} onChange={e => setBuilder({ ...builder, toolName: e.target.value })} /></label>
              </div>
              <label className="field"><span>Tool Description</span><input required value={builder.toolDesc} onChange={e => setBuilder({ ...builder, toolDesc: e.target.value })} /></label>
              <label className="field"><span>Async JS Handler Body</span><textarea className="mono" rows={3} required value={builder.handlerCode} onChange={e => setBuilder({ ...builder, handlerCode: e.target.value })} /></label>
              <button className="btn-primary" disabled={!!busy}>{busy === 'scaffold' ? 'Scaffolding…' : 'Build & Connect Local MCP'}</button>
            </form>

            {state.mcpServers.map(srv => {
              const status = state.mcpStatus?.[srv.name] || {};
              return (
                <section key={srv.name} className="panel-card">
                  <div className="row-between" style={{ marginBottom: 6 }}>
                    <strong style={{ fontSize: 14 }}>{srv.name}</strong>
                    <span className={`pill ${status.status === 'connected' ? 'ok' : status.status === 'error' ? 'err' : ''}`}>{status.status || 'disconnected'}</span>
                  </div>
                  <p className="hint mono">{srv.transport === 'stdio' ? `${srv.command} ${(srv.args || []).join(' ')}` : srv.url}</p>
                  <div className="row" style={{ marginBottom: 8 }}>
                    <button type="button" className="btn-secondary" disabled={!!busy} onClick={() => runServer(srv.name, 'connectMcp')}><Plug size={13} /> Connect</button>
                    <button type="button" className="btn-secondary" disabled={!!busy} onClick={() => runServer(srv.name, 'disconnectMcp')}><Unplug size={13} /> Disconnect</button>
                    <button type="button" className="btn-secondary" onClick={() => setForm({ ...emptyForm, ...srv, args: JSON.stringify(srv.args || []), envSecrets: JSON.stringify(srv.envSecrets || {}) })}>Edit</button>
                    <button type="button" className="btn-danger" disabled={!!busy} onClick={() => runServer(srv.name, 'removeMcp')}><Trash2 size={13} /></button>
                  </div>
                  {status.error && <p className="pill err" style={{ display: 'block', marginBottom: 8 }}>{status.error}</p>}
                  {status.tools?.length > 0 && (
                    <details style={{ marginBottom: 6 }}>
                      <summary className="hint">{status.toolCount ?? status.tools.length} tools · {status.resources?.length || 0} resources · {status.prompts?.length || 0} prompts</summary>
                      <McpCatalog server={srv.name} />
                    </details>
                  )}
                  {status.logs?.length > 0 && (
                    <details>
                      <summary className="hint"><Terminal size={12} style={{ verticalAlign: 'middle' }} /> Live stderr logs ({status.logs.length})</summary>
                      <pre className="pre-box" style={{ maxHeight: 160, marginTop: 6 }}>{status.logs.join('\n')}</pre>
                    </details>
                  )}
                </section>
              );
            })}
          </div>
        </div>
      </div>
    </div>
  );
}
